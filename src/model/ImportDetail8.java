package model;

public class ImportDetail8 {
    private int importDetailId;
    private int quantity;

    public ImportDetail8() {
    }

    public ImportDetail8(int importDetailId, int quantity) {
        this.importDetailId = importDetailId;
        this.quantity = quantity;
    }

    public int getImportDetailId() {
        return importDetailId;
    }

    public void setImportDetailId(int importDetailId) {
        this.importDetailId = importDetailId;
    }

    public int getQuantity() {
        return quantity;
    }

    public void setQuantity(int quantity) {
        this.quantity = quantity;
    }
}
